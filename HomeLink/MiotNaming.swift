/// MIoT 规范里的字段名、枚举值和单位都是英文，这里统一翻成中文。
///
/// 表里的键取自 miot-spec.org 官方设备描述里真实出现的名称与枚举。
/// 命中顺序：整名精确表 → 逐词拆词（标识符 → 英文描述）→ 原样兜底，
/// 所以即使厂商自定义了没收录的字段，也尽量拼出中文。
enum MiotNaming {
    static func identifier(_ urn: String) -> String {
        let parts = urn.split(separator: ":")
        guard parts.count > 3 else { return urn }
        return String(parts[3])
    }

    /// 服务、属性、动作的统一标题。
    static func title(type: String, fallback: String) -> String {
        let key = identifier(type)
        if let name = names[key] { return name }
        var best: (text: String, hit: Int, total: Int)?
        for candidate in [key, fallback] where !candidate.isEmpty {
            guard let composed = compose(candidate) else { continue }
            if composed.hit == composed.total { return composed.text }
            if best == nil || composed.hit > best!.hit { best = composed }
        }
        if let best, best.hit > 0 { return best.text }
        return fallback.isEmpty ? key : fallback
    }

    /// value-list 里的英文选项。
    static func optionTitle(_ raw: String) -> String {
        let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard text.contains(where: { $0.isLetter && $0.isASCII }) else { return text }
        let key = normalized(text)
        if let name = options[key] ?? words[key] { return name }
        if let name = patterned(key) { return name }
        var best: (text: String, hit: Int, total: Int)?
        for candidate in [normalized(camelSpaced(text)), key] {
            guard let composed = composeOption(candidate) else { continue }
            if composed.hit == composed.total, composed.total > 0 { return composed.text }
            if best == nil || composed.hit > best!.hit { best = composed }
        }
        if let best, best.hit > 0 { return best.text }
        return text
    }

    static func unitSuffix(_ unit: String?) -> String {
        guard let unit else { return "" }
        return units[unit] ?? ""
    }

    // MARK: - 内部

    private static func normalized(_ text: String) -> String {
        let lowered = text.lowercased().map { char -> Character in
            "-_/,()[]".contains(char) ? " " : char
        }
        return String(lowered).split(separator: " ").joined(separator: " ")
    }

    private static func camelSpaced(_ text: String) -> String {
        var output = ""
        let characters = Array(text)
        for (index, char) in characters.enumerated() {
            if index > 0, char.isUppercase,
               characters[index - 1].isLowercase || characters[index - 1].isNumber {
                output.append(" ")
            }
            output.append(char)
        }
        return output
    }

    private static func patterned(_ key: String) -> String? {
        let compact = key.replacingOccurrences(of: " ", with: "")
        let patterns: [(String, String)] = [
            ("^level(\\d+)$", "档位"),
            ("^mode(\\d+)$", "模式"),
            ("^fault(\\d+)$", "故障"),
            ("^l(\\d+)$", "档位"),
        ]
        for (pattern, prefix) in patterns {
            guard let regex = try? NSRegularExpression(pattern: pattern) else { continue }
            let range = NSRange(compact.startIndex..., in: compact)
            guard let match = regex.firstMatch(in: compact, range: range),
                  let captured = Range(match.range(at: 1), in: compact) else { continue }
            return prefix + compact[captured]
        }
        let durations: [(String, String)] = [
            ("^(\\d+)(seconds?|sec)$", " 秒"),
            ("^(\\d+)(minutes?|min)$", " 分钟"),
            ("^(\\d+)(hours?|hr)$", " 小时"),
            ("^(\\d+)(days?)$", " 天"),
        ]
        for (pattern, suffix) in durations {
            guard let regex = try? NSRegularExpression(pattern: pattern) else { continue }
            let range = NSRange(compact.startIndex..., in: compact)
            guard let match = regex.firstMatch(in: compact, range: range),
                  let captured = Range(match.range(at: 1), in: compact) else { continue }
            return compact[captured] + suffix
        }
        return nil
    }

    private static func compose(_ text: String) -> (text: String, hit: Int, total: Int)? {
        compose(text, table: words)
    }

    private static func composeOption(_ text: String) -> (text: String, hit: Int, total: Int)? {
        var best = compose(text, table: options)
        if let other = compose(text, table: words) {
            if best == nil || other.hit > best!.hit { best = other }
        }
        return best
    }

    private static func compose(
        _ text: String,
        table: [String: String]
    ) -> (text: String, hit: Int, total: Int)? {
        let parts = text.lowercased().split { $0 == "-" || $0 == "_" || $0 == " " }.map(String.init)
        guard !parts.isEmpty else { return nil }
        var output = ""
        var hit = 0
        for part in parts {
            if part.allSatisfy({ $0.isNumber || $0 == "." }) {
                output += part
                hit += 1
            } else if let word = table[part] {
                output += word
                hit += 1
            } else {
                output += part
            }
        }
        return hit > 0 ? (output, hit, parts.count) : nil
    }

    /// 分块表合并：大字典拆开写，编译时类型检查才不至于卡住。
    private static func merge(_ chunks: [[String: String]]) -> [String: String] {
        var result: [String: String] = [:]
        for chunk in chunks { result.merge(chunk) { current, _ in current } }
        return result
    }

